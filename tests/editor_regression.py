"""Editor history, large graphs, directory, and mocked AI; never calls a provider."""
import argparse, json, os
from pathlib import Path
from playwright.sync_api import sync_playwright

parser=argparse.ArgumentParser()
parser.add_argument('--output', type=Path, required=True)
args=parser.parse_args()
args.output.mkdir(parents=True, exist_ok=True)
root=Path(__file__).resolve().parents[1]
checks=[]
def check(name, value):
    assert value, name
    checks.append(name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True, executable_path=os.environ.get('STORY_BROWSER_EXECUTABLE'))
    context=browser.new_context(viewport={'width':1440,'height':900})
    page=context.new_page()
    errors=[]
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('dialog', lambda d: d.accept())
    page.goto((root/'src/index.html').as_uri())
    page.click('#empty-create')
    page.locator('#nd-text').blur()
    page.click('#btn-undo')
    check('new scene undo returns to empty',page.evaluate('nodes.length===0'))
    page.click('#btn-redo')
    check('new scene redo',page.evaluate('nodes.length===1'))
    page.evaluate('showSampleStory();select(nodes[0],null)')
    initial=page.evaluate('serializeState()')
    page.click('#nd-del')
    page.click('#btn-undo')
    check('delete undo restores scene and edges',page.evaluate('serializeState()')==initial)
    page.click('#btn-redo')
    check('delete redo',page.evaluate('nodes.length===5'))
    page.click('#btn-undo')
    page.evaluate('select(nodes[0],null)')
    original_text=page.evaluate('nodes[0].text')
    page.fill('#nd-text','第一段')
    page.fill('#nd-text','修改后的场景')
    page.click('#btn-undo')
    check('typing undo grouped per field',page.evaluate('nodes[0].text')==original_text)
    page.click('#btn-redo')
    check('typing redo',page.evaluate("nodes[0].text==='修改后的场景'"))
    page.evaluate('fitView();select(nodes[0],null)')
    pos=page.evaluate('({x:nodes[0].x,y:nodes[0].y,sx:w2s(nodes[0].x,nodes[0].y).x,sy:w2s(nodes[0].x,nodes[0].y).y})')
    box=page.locator('#canvas').bounding_box()
    page.mouse.move(box['x']+pos['sx'],box['y']+pos['sy'])
    page.mouse.down()
    page.mouse.move(box['x']+pos['sx']+50,box['y']+pos['sy']+30,steps=8)
    page.mouse.up()
    check('canvas drag moves scene',page.evaluate('nodes[0].x')!=pos['x'])
    page.click('#btn-undo')
    check('canvas drag undo restores position',page.evaluate('({x:nodes[0].x,y:nodes[0].y})')=={'x':pos['x'],'y':pos['y']})
    page.evaluate("entities.characters.Test={desc:'history'};aiConfig.world={name:'history'};save();undo()")
    check('history restores entity and world data',page.evaluate("!entities.characters.Test&&!aiConfig.world"))
    page.evaluate("select(nodes[0],null);nodes[0].notes='different branch';save()")
    check('new edit discards redo branch',page.locator('#btn-redo').is_disabled())
    page.evaluate("select(nodes[0],null);nodes[0].items=[{name:'钥匙',qty:1}];nodes[0].setFlags=['出发'];nodes[0].body='目录检索的正文暗号';save()")
    page.click('#nd-copy')
    check('copy preserves metadata without edges',page.evaluate("nodes.length===7&&edges.length===5&&selNode.body==='目录检索的正文暗号'&&selNode.items[0].name==='钥匙'&&selNode.items!==nodes[0].items&&selNode.setFlags!==nodes[0].setFlags"))
    page.click('#btn-undo')
    check('copy is one undo step',page.evaluate('nodes.length===6'))
    page.keyboard.press('Control+k')
    check('directory shortcut',page.locator('#scene-directory').is_visible())
    page.fill('#scene-search','正文暗号')
    page.wait_for_function("document.querySelectorAll('.scene-row').length===1")
    check('directory searches body',page.locator('.scene-jump').count()==1)
    page.locator('.scene-row button').last.click()
    page.select_option('#scene-filter','bookmarks')
    page.wait_for_timeout(180)
    check('directory bookmark filter',page.locator('.scene-jump').count()==1)
    page.locator('.scene-jump').click()
    check('directory jump selects matching scene',page.evaluate('selNode===nodes[0]'))
    page.locator('.scene-jump').focus()
    page.keyboard.press('Tab')
    check('directory tab navigation does not create scenes',page.evaluate('nodes.length===6'))
    page.click('#scene-close')
    page.evaluate("apiCfg.endpoint='https://example.invalid/v1';apiCfg.key='test-only';aiConfig.generationParams.temperature=0;aiConfig.generationParams.branchCount=2;aiConfig.world={name:'测试世界'};window.__requests=[];window.fetch=async(url,options)=>{window.__requests.push(JSON.parse(options.body));return {ok:true,json:async()=>({choices:[{message:{content:JSON.stringify([{text:'AI 场景 A',body:'完整正文',characters:['甲'],probability:0,label:'等待',category:'daily'},{text:'AI 场景 B',probability:100,label:'前进',category:'ending'}])}}]})}};void 0")
    page.click('#nd-ai')
    page.wait_for_selector('#ai-results .ai-card')
    check('AI respects configured temperature and world',page.evaluate("window.__requests[0].temperature===0&&window.__requests[0].messages[0].content.includes('测试世界')&&window.__requests[0].messages[1].content.includes('Generate 2')"))
    page.evaluate('window.__origin=selNode.id;select(nodes[1],null)')
    page.locator('#ai-results > .ai-apply').click()
    check('AI applies to captured origin with zero probability',page.evaluate("nodes.length===8&&edges.at(-2).from===window.__origin&&edges.at(-2).probability===0&&nodes.at(-2).body==='完整正文'"))
    check('AI all apply disabled after use',page.locator('#ai-results > .ai-apply').is_disabled())
    page.click('#btn-undo')
    check('AI apply all is one undo step',page.evaluate('nodes.length===6&&edges.length===5'))
    # Failure, retry, cancellation, stale document, and malformed response.
    page.evaluate("select(nodes[0],null);window.fetch=async()=>({ok:false,status:429});void 0")
    page.click('#nd-ai')
    page.wait_for_selector('#ai-results > button')
    check('AI actionable rate limit error and retry', '额度不足' in page.locator('#ai-results').inner_text() and '重新生成' in page.locator('#ai-results').inner_text())
    page.evaluate("window.fetch=(url,options)=>new Promise((resolve,reject)=>{window.__resolveAI=resolve;options.signal.addEventListener('abort',()=>reject(new DOMException('cancelled','AbortError')));});void 0")
    page.click('#ai-results > button')
    page.wait_for_selector('#ai-job',state='visible')
    page.click('#ai-cancel')
    page.wait_for_function("!document.getElementById('nd-ai').disabled")
    check('AI cancellation recovers controls','已取消' in page.locator('#ai-results').inner_text() and not page.locator('#ai-job').is_visible())
    page.click('#nd-ai')
    page.wait_for_selector('#ai-job',state='visible')
    page.evaluate('fileNew()')
    page.wait_for_function("!document.getElementById('nd-ai').disabled")
    check('opening new story cancels pending generation',page.evaluate('nodes.length===0') and not page.locator('#ai-job').is_visible())
    page.evaluate("showSampleStory();select(nodes[0],null);window.fetch=async()=>({ok:true,json:async()=>({choices:[{message:{content:'[{\"text\":42}]'}}]})});void 0")
    page.click('#nd-ai')
    page.wait_for_function("!document.getElementById('nd-ai').disabled")
    check('malformed AI branch rejected without mutation',page.evaluate('nodes.length===6') and '缺少场景摘要' in page.locator('#ai-results').inner_text())
    page.evaluate("window.fetch=async()=>({ok:true,json:async()=>({choices:[{message:{content:'[]'}}]})});runCheck();void 0")
    page.click('#btn-ai-check')
    page.wait_for_function("!document.getElementById('btn-ai-check').disabled")
    check('empty consistency result restores check button','未发现' in page.locator('#ai-check-res').inner_text())
    page.evaluate("document.getElementById('check-panel').classList.remove('show')")
    check('branch context excludes unrelated scenes',page.evaluate("(()=>{apiCfg.contextMode='branch';const n=addNode(100,100,'无关暗号');save();return !buildTreeContext(nodes[0]).includes('无关暗号')})()"))
    check('whole story context includes unrelated scenes',page.evaluate("apiCfg.contextMode='all';buildTreeContext(nodes[0]).includes('无关暗号')"))
    page.evaluate("loadData({version:2,nodes:[{id:1,text:'子图入口',group:'第一章'},{id:2,text:'隐藏场景',parentGroup:'第一章'}],edges:[]});currentScope='别的章节';collapsed.add(1);focusScene(nodes[1])")
    check('directory reveals correct subgraph',page.evaluate("currentScope==='第一章'&&selNode.id===2&&nodeVis(selNode)"))
    page.evaluate("loadData({version:2,nodes:[{id:1,text:'一'},{id:2,text:'二'}],edges:[{id:1,from:1,to:2},{id:2,from:2,to:1}]})")
    check('cyclic descendants terminate and exclude origin',page.evaluate('getDesc(1).size===1&&!getDesc(1).has(1)'))
    page.evaluate("loadData({version:2,nodes:[{id:1},{id:2},{id:3}],edges:[{id:1,from:1,to:2},{id:2,from:2,to:3}]});collapsed.add(1);collapsed.add(2)")
    check('nested collapse stays hidden behind parent',page.evaluate('!isHidden(1)&&isHidden(2)&&isHidden(3)'))
    # Deterministic large graph workload, recording rather than asserting machine-dependent timings.
    timing=page.evaluate('''() => {
      const count=600;loadData({version:2,nodes:Array.from({length:count},(_,i)=>({id:i+1,text:'场景 '+i,x:(i%15)*240,y:Math.floor(i/15)*120})),edges:Array.from({length:count-1},(_,i)=>({id:i+1,from:i+1,to:i+2,probability:100}))});
      collapsed.add(1);const timings=[];for(let i=0;i<7;i++){const start=performance.now();render();timings.push(performance.now()-start)}return timings.sort((a,b)=>a-b)[3];
    }''')
    page.evaluate("toggleSceneDirectory(true);document.getElementById('scene-search').value='';document.getElementById('scene-filter').value='all';renderSceneList()")
    check('large directory bounds initial DOM size',page.locator('.scene-row').count()==100)
    page.get_by_text('显示更多场景',exact=True).click()
    check('directory loads more on demand',page.locator('.scene-row').count()==200)
    check('large context stays bounded',page.evaluate('buildTreeContext(nodes[0]).length<18200'))
    # Save races use a simulated native bridge. Real native I/O has a separate test.
    native=context.new_page()
    native.add_init_script("window.__TAURI__={window:{getCurrentWindow:()=>({setTitle:async()=>{},onCloseRequested:async()=>{}})},fs:{writeTextFile:()=>new Promise(r=>window.__finishWrite=r)}}")
    native.goto((root/'src/index.html').as_uri())
    native.evaluate("loadData({version:2,nodes:[{id:1,text:'old'}],edges:[]});currentFile='/old.json';window.__save=fileSave();void 0")
    native.wait_for_function('typeof window.__finishWrite===\"function\"')
    native.evaluate("loadData({version:2,nodes:[{id:2,text:'new'}],edges:[]});currentFile='/new.json';markClean();window.__finishWrite()")
    native.evaluate('window.__save')
    check('old save cannot mark another document dirty or change filename',native.evaluate("!dirty&&currentFile==='/new.json'&&nodes[0].text==='new'"))
    native.evaluate("window.__writes=[];window.__finishWrite=null;window.__TAURI__.fs.writeTextFile=(path,data)=>{window.__writes.push(JSON.parse(data).nodes[0].text);return new Promise(r=>window.__finishWrite=r)};nodes[0].text='first';window.__first=fileSave();nodes[0].text='second';window.__second=fileSave();void 0")
    native.wait_for_function('window.__writes.length===1')
    native.evaluate('window.__finishWrite()')
    native.wait_for_function('window.__writes.length===2')
    native.evaluate('window.__finishWrite()')
    native.evaluate('window.__second')
    check('file writes preserve request ordering',native.evaluate("window.__writes.join(',')==='first,second'&&!dirty"))
    native.close()
    page.evaluate('showSampleStory();select(nodes[0],null);toggleSceneDirectory(true);fitView()')
    for width,height,name in [(1440,900,'wide'),(800,600,'compact'),(390,844,'mobile')]:
        page.set_viewport_size({'width':width,'height':height})
        page.screenshot(path=str(args.output/('editor-'+name+'.png')))
        check('no overflow '+name,page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('no runtime errors',not errors)
    browser.close()
report={'passed':len(checks),'checks':checks,'collapsed_600_nodes_render_median_ms':timing}
(args.output/'editor-results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(report,ensure_ascii=False))
