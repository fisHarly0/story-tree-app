"""Exercise real pointer and keyboard gestures on the story canvas."""
import argparse,json,os
from pathlib import Path
from playwright.sync_api import sync_playwright

parser=argparse.ArgumentParser()
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
args.output.mkdir(parents=True,exist_ok=True)
root=Path(__file__).resolve().parents[1]
checks=[]
def check(name,value):
    assert value,name
    checks.append(name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('STORY_BROWSER_EXECUTABLE'))
    page=browser.new_page(viewport={'width':1440,'height':900})
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('dialog',lambda dialog:dialog.accept())
    page.goto((root/'src/index.html').as_uri())
    def fixture():
        page.evaluate("loadData({version:2,nodes:[{id:1,text:'起点',x:-220,y:0},{id:2,text:'第二幕',x:220,y:0},{id:3,text:'另一条路线',x:0,y:240}],edges:[]});pan={x:cvs.clientWidth/2,y:180};zoom=1;setMode('select');select(null,null);markClean();render();cvs.focus()")
    def point(id,handle=False):
        return page.evaluate("([id,handle])=>{const n=nodes.find(n=>n.id===id),p=w2s(n.x,n.y+(handle?n.h/2:0)),r=cvs.getBoundingClientRect();return {x:p.x+r.left,y:p.y+r.top}}",[id,handle])
    def canvas_point(x,y):
        box=page.locator('#canvas').bounding_box()
        return {'x':box['x']+x,'y':box['y']+y}
    def click(pt,**kwargs):page.mouse.click(pt['x'],pt['y'],**kwargs)
    def drag(a,b):
        page.mouse.move(a['x'],a['y']);page.mouse.down();page.mouse.move(b['x'],b['y'],steps=8);page.mouse.up()

    fixture()
    click(point(1))
    check('select exposes contextual actions',page.locator('#node-actions').is_visible())
    oldpan=page.evaluate('({...pan})')
    page.keyboard.down('Space')
    a=point(1);drag(a,{'x':a['x']+80,'y':a['y']+35})
    page.keyboard.up('Space')
    check('space drag pans over a scene without moving it',page.evaluate('nodes[0].x===-220&&nodes[0].y===0&&selNode.id===1') and page.evaluate('pan.x')==oldpan['x']+80)
    check('space released restores cursor',page.evaluate("!spaceHeld&&wrap.style.cursor==='default'"))
    fixture();click(point(1));page.keyboard.down('Shift');click(point(2));page.keyboard.up('Shift')
    check('shift click builds multiselection',page.evaluate('multiSel.size===2'))
    a=point(1);drag(a,{'x':a['x']+60,'y':a['y']+40})
    check('dragging selection moves both scenes',page.evaluate('nodes[0].x===-160&&nodes[1].x===280&&nodes[0].y===40&&nodes[1].y===40&&nodes[2].x===0&&multiSel.size===2'))
    page.keyboard.press('Control+z')
    check('one undo restores the whole drag',page.evaluate('nodes[0].x===-220&&nodes[1].x===220&&nodes[0].y===0&&nodes[1].y===0'))
    fixture();page.keyboard.down('Shift');drag(canvas_point(100,100),canvas_point(1000,230));page.keyboard.up('Shift')
    check('shift drag box selects intersecting scenes',page.evaluate('multiSel.size===2&&multiSel.has(1)&&multiSel.has(2)'))
    fixture();a=point(1);page.mouse.move(a['x'],a['y']);page.mouse.down();page.mouse.move(a['x']+100,a['y']+70,steps=5);page.keyboard.press('Escape');page.mouse.up()
    check('escape rolls back active move',page.evaluate('nodes[0].x===-220&&nodes[0].y===0&&!canvasGesture&&!dirty'))
    fixture();a=point(1);page.mouse.move(a['x'],a['y']);page.mouse.down();page.mouse.move(a['x']+50,a['y']+20)
    page.evaluate("cvs.dispatchEvent(new PointerEvent('pointercancel',{pointerId:canvasGesture.pointerId}))")
    page.mouse.up()
    check('pointer cancellation rolls back move',page.evaluate('nodes[0].x===-220&&nodes[0].y===0&&!canvasGesture'))
    fixture();a=point(1);page.mouse.move(a['x'],a['y']);page.mouse.down();page.mouse.move(a['x']+40,a['y']+30);page.evaluate("window.dispatchEvent(new Event('blur'))");page.mouse.up()
    check('window focus loss releases drag safely',page.evaluate('nodes[0].x===-220&&!canvasGesture&&!spaceHeld'))
    fixture();drag(point(1,True),point(2))
    check('drag connector links existing scenes',page.evaluate('edges.length===1&&edges[0].from===1&&edges[0].to===2&&selEdge===edges[0]'))
    click(point(1));drag(point(1,True),point(2))
    check('duplicate connection gives feedback without extra edge',page.evaluate('edges.length===1') and '已经相连' in page.locator('#canvas-hint').inner_text())
    click(point(1));drag(point(1,True),point(1))
    check('self connection is rejected',page.evaluate('edges.length===1'))
    fixture();a=point(1,True);drag(a,{'x':a['x'],'y':a['y']+180})
    check('drop on blank creates linked scene and enters edit',page.evaluate('nodes.length===4&&edges.length===1&&edges[0].from===1&&edges[0].to===selNode.id') and page.locator('#inline-edit').evaluate('(el)=>el===document.activeElement'))
    page.fill('#inline-edit','下一幕的摘要');page.keyboard.press('Control+Enter')
    check('ctrl enter commits inline draft',page.evaluate("nodes.at(-1).text==='下一幕的摘要'&&!editingNode") and page.locator('#canvas').evaluate('(el)=>el===document.activeElement'))
    page.keyboard.press('Control+z');page.keyboard.press('Control+z')
    check('created branch can be fully undone',page.evaluate('nodes.length===3&&edges.length===0'))
    fixture();a=point(1,True);page.mouse.move(a['x'],a['y']);page.mouse.down();page.mouse.move(a['x']+160,a['y']+100);page.keyboard.press('Escape');page.mouse.up()
    check('escape cancels pending connector',page.evaluate('nodes.length===3&&edges.length===0&&!dragEdgeFrom&&!canvasGesture'))
    fixture();drag(point(1,True),{'x':1400,'y':350})
    check('drop outside canvas does not create an invisible scene',page.evaluate('nodes.length===3&&edges.length===0&&!canvasGesture'))
    fixture();page.evaluate('zoom=.4;render()');a=point(1,True);a['y']+=9;drag(a,point(2))
    check('connector hit area stays usable while zoomed out',page.evaluate('edges.length===1&&edges[0].from===1&&edges[0].to===2'))
    fixture();click(point(1));page.click('#quick-next')
    check('context action creates next scene',page.evaluate('nodes.length===4&&edges[0].from===1') and page.locator('#inline-edit').evaluate('(el)=>el===document.activeElement'))
    page.keyboard.press('Escape');page.keyboard.press('Tab')
    check('canvas tab continues from selected scene',page.evaluate('nodes.length===5&&edges.length===2') and page.locator('#inline-edit').evaluate('(el)=>el===document.activeElement'))
    page.keyboard.press('Escape');page.keyboard.press('Enter');page.fill('#inline-edit','未提交');page.keyboard.press('Escape')
    check('escape discards inline text draft',page.evaluate("nodes.at(-1).text===''&&!editingNode"))
    fixture();click(point(1));page.click('#quick-connect');click(point(2))
    check('two click connection returns to selection mode',page.evaluate("edges.length===1&&mode==='select'&&!connFrom"))
    fixture();click(point(1));page.click('#quick-connect');page.keyboard.press('Escape')
    check('escape cancels connection mode but preserves origin selection',page.evaluate("mode==='select'&&selNode.id===1&&edges.length===0"))
    fixture();page.keyboard.press('Control+a')
    check('canvas select all targets visible scenes',page.evaluate('multiSel.size===3'))
    page.keyboard.press('Delete');page.keyboard.press('Control+z')
    check('bulk delete is reversible',page.evaluate('nodes.length===3'))
    click(point(1));page.fill('#nd-text','文字');page.keyboard.press('n');page.keyboard.press('Space');page.keyboard.press('c')
    check('canvas shortcuts do not capture typing',page.evaluate("nodes.length===3&&!spaceHeld&&mode==='select'") and page.locator('#nd-text').input_value()=='文字n c')
    page.locator('#nd-text').blur();page.locator('#canvas').focus();page.keyboard.press('n')
    check('N creates scene at viewport center',page.evaluate('nodes.length===4') and page.locator('#inline-edit').evaluate('(el)=>el===document.activeElement'))
    page.keyboard.press('Escape')
    fixture();click(canvas_point(page.locator('#canvas').bounding_box()['width']-10,120),button='right')
    menu=page.locator('#ctx-menu').bounding_box();box=page.locator('#canvas').bounding_box()
    check('right click opens menu inside canvas',page.locator('#ctx-menu').is_visible() and menu['x']+menu['width']<=box['x']+box['width'])
    page.keyboard.press('Enter')
    check('context menu works from keyboard',page.evaluate('nodes.length===4') and page.locator('#inline-edit').evaluate('(el)=>el===document.activeElement'))
    page.keyboard.press('Escape')
    fixture();a=canvas_point(450,350);click(a)
    before=page.evaluate('s2w(450,350)');page.mouse.move(a['x'],a['y']);page.mouse.wheel(0,-120);page.wait_for_timeout(100)
    after=page.evaluate('s2w(450,350)')
    check('wheel zoom anchors pointer world position',abs(before['x']-after['x'])<.001 and abs(before['y']-after['y'])<.001 and page.evaluate('zoom>1'))
    page.click('#zoom-reset');check('zoom reset returns to 100 percent',page.evaluate('zoom===1'))
    oldwidth=page.locator('#canvas').bounding_box()['width'];page.click('#btn-focus-view')
    check('focus canvas hides inspector and reallocates width',not page.locator('#panel').is_visible() and page.locator('#canvas').bounding_box()['width']>oldwidth)
    page.click('#btn-focus-view');check('inspector can be restored',page.locator('#panel').is_visible())
    page.click('#btn-file-menu');check('file actions remain reachable',page.locator('#btn-export').is_visible())
    page.keyboard.press('Escape');check('menu escape restores trigger focus',not page.locator('#file-tools').is_visible() and page.locator('#btn-file-menu').evaluate('(el)=>el===document.activeElement'))
    page.click('#btn-tools-menu');page.click('#btn-layout');check('secondary tool runs and closes menu',not page.locator('#story-tools').is_visible())
    check('completed menu action returns focus to canvas',page.locator('#canvas').evaluate('(el)=>el===document.activeElement'))
    page.locator('#btn-save').focus();page.keyboard.press('Control+z')
    check('undo shortcut works after toolbar interaction',page.evaluate('nodes[0].x===-220&&nodes[1].x===220'))
    fixture();click(point(1));page.click('#quick-connect')
    page.evaluate("loadData({version:2,nodes:[{id:20,text:'新文件'}],edges:[]})")
    check('opening document clears old connection source',page.evaluate("mode==='select'&&!connFrom&&!dragEdgeFrom"))
    page.evaluate('select(nodes[0],null);showInlineEdit(nodes[0])');page.fill('#inline-edit','旧文件草稿')
    page.evaluate("loadData({version:2,nodes:[{id:30,text:'又一份文件'}],edges:[]})")
    check('opening document dismisses stale inline draft',page.evaluate("!editingNode&&nodes[0].text==='又一份文件'") and not page.locator('#inline-edit').is_visible())
    # One batched visual inspection across window sizes and theme.
    page.evaluate('showSampleStory();toggleSceneDirectory(false);fitView();select(nodes[1],null)')
    for width,height,name in [(1440,900,'wide'),(800,600,'compact'),(390,844,'mobile')]:
        page.set_viewport_size({'width':width,'height':height});page.evaluate('fitView()')
        page.screenshot(path=str(args.output/('canvas-'+name+'.png')))
        check('no horizontal overflow '+name,page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':1440,'height':900});page.click('#btn-tools-menu');page.click('#btn-theme');page.evaluate('fitView()');page.wait_for_timeout(180)
    page.screenshot(path=str(args.output/'canvas-light.png'))
    check('light theme uses readable connector colors',page.evaluate("probColor(100)==='#25613a'&&probColor(50)==='#79500d'"))
    check('no runtime errors',not errors)
    browser.close()
report={'passed':len(checks),'checks':checks}
(args.output/'canvas-results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(report,ensure_ascii=False))
